export const BUILTIN_RULES: readonly RedactionRuleDefinition[] = RULES.map(({ slug, ...rule }) => ({
  ...rule,
  id: `builtin:${slug}`,
  source: "builtin" as const,
}));

export function isBuiltinRuleEnabled(
  rule: RedactionRuleDefinition,
  overrides: Record<string, boolean>
): boolean {
  const override = overrides[rule.id];
  return typeof override === "boolean" ? override : rule.defaultEnabled !== false;
}
